def distancia(a, b):
    return sum((x - y) * (x - y) for x, y in zip(a, b))


def predecir(huella):
    # las K fotos de entrenamiento más cercanas; a igual distancia,
    # la que va antes en ENTRENO
    vecinas = sorted(
        (distancia(h, huella), i, gesto)
        for i, (_, gesto, _, h) in enumerate(ENTRENO)
    )[:K]
    votos = {}
    for d, _, gesto in vecinas:
        n, suma = votos.get(gesto, (0, 0))
        votos[gesto] = (n + 1, suma + d)
    # más votos; si empatan, menos distancia; si no, el orden de CLASES
    return min(votos, key=lambda g: (-votos[g][0], votos[g][1],
                                     CLASES.index(g)))


def cifra(bien, total):
    decimas = (2000 * bien + total) // (2 * total)
    return f"{bien} de {total} ({decimas // 10},{decimas % 10} %)"


def acierto(fotos):
    return sum(1 for _, gesto, _, h in fotos if predecir(h) == gesto)


